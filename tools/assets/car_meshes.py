"""
Collects the prepared car meshes into one Luau data module for the Studio builder: for each
archetype, the uploaded model's asset id, what every part is for (from the manifest
tools/blender/prepare_car.py wrote), and the author credit from the Sketchfab download.
Also rewrites CREDITS.md, since every model's licence asks for attribution.

    python -I tools/assets/car_meshes.py <prepared dir> <downloads dir> <asset ids json> \
        <out.luau> <credits.md>

The asset ids JSON maps archetype to asset id, as tools/assets/upload_images.py prints it.
"""

import json
import sys
from pathlib import Path


def luau_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    prepared, downloads, ids_path, out, credits_path = (Path(arg) for arg in sys.argv[1:6])
    ids = json.loads(ids_path.read_text())
    lines = [
        "--!strict",
        "-- Generated by tools/assets/car_meshes.py. Do not edit by hand.",
        "return {",
    ]
    credits = [
        "# Credits",
        "",
        "Car models are adapted from these Sketchfab models under their Creative Commons",
        "licences (reduced, split into parts and recoloured for the game):",
        "",
    ]
    for archetype in sorted(ids):
        asset = ids[archetype]
        if not str(asset).isdigit():
            continue
        manifest = json.loads((prepared / archetype / "manifest.json").read_text())
        credit = json.loads((downloads / archetype / "credit.json").read_text())
        lines.append(f"\t{archetype} = {{")
        lines.append(f"\t\tasset = {asset},")
        lines.append(f"\t\tsourceLength = {manifest['length']},")
        lines.append(f"\t\tcredit = {luau_string(credit['name'] + ' by ' + credit['author'])},")
        lines.append("\t\tparts = {")
        for part in manifest["parts"]:
            lines.append(
                f"\t\t\t[{luau_string(part['name'])}] = {{ role = {luau_string(part['role'])}, "
                f"color = {luau_string(part['color'])}, transparency = {part['transparency']}, "
                f"textured = {'true' if part['textured'] else 'false'} }},"
            )
        lines.append("\t\t},")
        lines.append("\t},")
        credits.append(f"- **{credit['name']}** by {credit['author']}, {credit['license']}: {credit['url']}")
    lines.append("}")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    credits_path.write_text("\n".join(credits) + "\n", encoding="utf-8")
    print(f"wrote {out} and {credits_path}")


if __name__ == "__main__":
    main()
